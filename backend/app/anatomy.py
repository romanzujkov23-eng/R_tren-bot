DEFAULTS: dict[str, tuple[float, ...]] = {
    "Грудные": (0.25, 0.50, 0.25),
    "Трапеции": (0.50, 0.35, 0.15),
    "Бицепс": (0.50, 0.50),
    "Трицепс": (0.35, 0.35, 0.30),
    "Предплечья": (0.60, 0.40),
    "Квадрицепс": (0.30, 0.35, 0.35),
    "Ягодичные": (0.75, 0.25),
    "Бицепс бедра": (0.50, 0.50),
    "Икры": (0.60, 0.40),
}


def region_id(parent: str, part: str) -> str:
    return f"{parent}: {part}"


ALL_REGIONS: list[tuple[str, str, str]] = [
    (region_id(p, part), p, part) for p, parts in REGIONS.items() for part in parts
]


def shares(parent: str, exercise_name: str) -> list[tuple[str, float]]:
    """Как нагрузка на мышцу делится между её частями для этого упражнения."""
    parts = REGIONS.get(parent)
    if not parts:
        return []
    name = exercise_name.lower()
    weights = DEFAULTS[parent]
    for words, w in RULES.get(parent, []):
        if any(k in name for k in words):
            weights = w
            break
    return [(region_id(parent, part), w) for part, w in zip(parts, weights) if w > 0]


def accumulate(items) -> dict[str, float]:
    """items: (название, основные, вспомогательные, число подходов) -> нагрузка по частям."""
    loads: dict[str, float] = {}
    for name, primary, secondary, count in items:
        for credit, muscles in ((1.0, primary), (ASSIST_WEIGHT, [m for m in secondary if m not in primary])):
            for m in muscles:
                for rid, w in shares(m, name):
                    loads[rid] = loads.get(rid, 0.0) + count * credit * w
    return loads


def regions_payload(loads: dict[str, float]) -> list[dict]:
    totals: dict[str, float] = {}
    for rid, parent, _ in ALL_REGIONS:
        totals[parent] = totals.get(parent, 0.0) + loads.get(rid, 0.0)
    return [
        {
            "name": rid,
            "parent": parent,
            "part": part,
            "load": round(loads.get(rid, 0.0), 1),
            "share": round(loads.get(rid, 0.0) / totals[parent], 3) if totals[parent] > 0 else 0.0,
        }
        for rid, parent, part in ALL_REGIONS
    ]
