"""Дробная анатомия: части мышц (головки, пучки, отделы).

В каталоге у упражнения указаны целые мышцы. Как нагрузка делится между их частями,
зависит от типа упражнения (наклон скамьи, хват, положение корпуса). Это оценка по
названию упражнения, а не измерение: правила ниже отражают общепринятую биомеханику.
Если для упражнения правила нет, нагрузка делится по стандартным долям.
Делим только мышцы, у которых есть самостоятельные части с разной функцией (головки, пучки, отделы).
Прямая мышца живота и широчайшая работают как единое целое, поэтому не делятся.
"""

ASSIST_WEIGHT = 0.5

