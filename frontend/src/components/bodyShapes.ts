function rp(pts: [number, number][], r = 2.2): string {
  const n = pts.length
  let d = ''
  for (let i = 0; i < n; i++) {
    const p0 = pts[(i + n - 1) % n], p1 = pts[i], p2 = pts[(i + 1) % n]
    const l1 = Math.hypot(p1[0] - p0[0], p1[1] - p0[1]), l2 = Math.hypot(p2[0] - p1[0], p2[1] - p1[1])
    const a = Math.min(r, l1 / 2.2), b = Math.min(r, l2 / 2.2)
    const s: [number, number] = [p1[0] + ((p0[0] - p1[0]) * a) / l1, p1[1] + ((p0[1] - p1[1]) * a) / l1]
    const e: [number, number] = [p1[0] + ((p2[0] - p1[0]) * b) / l2, p1[1] + ((p2[1] - p1[1]) * b) / l2]
    d += `${i ? 'L' : 'M'}${s[0].toFixed(1)} ${s[1].toFixed(1)}Q${p1[0]} ${p1[1]} ${e[0].toFixed(1)} ${e[1].toFixed(1)}`
  }
  return d + 'Z'
}

