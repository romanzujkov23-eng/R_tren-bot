const cache = new Map<string, [number, number] | null>()
let ctx: CanvasRenderingContext2D | null | undefined

/** Центр видимой части мышцы для подписи на карте. */
export function anchorOf(d: string): [number, number] | null {
  if (cache.has(d)) return cache.get(d)!
  let res: [number, number] | null = null
  if (ctx === undefined) {
    ctx = typeof document !== 'undefined' && typeof Path2D !== 'undefined' ? document.createElement('canvas').getContext('2d') : null
  }
  if (ctx) {
    const path = new Path2D(d)
    const nums = (d.match(/-?\d+(?:\.\d+)?/g) ?? []).map(Number)
    const xs = nums.filter((_, i) => i % 2 === 0)
    const ys = nums.filter((_, i) => i % 2 === 1)
    let sx = 0
    let sy = 0
    let c = 0
    for (let x = Math.min(...xs); x <= Math.max(...xs); x += 1) {
      for (let y = Math.min(...ys); y <= Math.max(...ys); y += 1) {
        if (ctx.isPointInPath(path, x, y)) {
          sx += x
          sy += y
          c++
        }
      }
    }
    if (c > 0) res = [sx / c, sy / c]
  }
  cache.set(d, res)
  return res
}
